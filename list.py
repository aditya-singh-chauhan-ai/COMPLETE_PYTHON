#DATA STRUCTURE
# ORDERED COLLECTION OF ITEMS
# WE CREATE A LIST USING SQUARE BRACKETS []
numbers = [1, 2, 3, 4, 5]
print(numbers[1])  # Output: [1, 2, 3, 4, 5]
words = ["apple," "banana", "cherry"] 
print(words[:2])  # Output: ['apple,banana', 'cherry']
mixed = [1, "hello", 3.14, True]
print(mixed[-1])  # Output: [1, 'hello', 3.14, True]
mixed[1:] = "world"
print(mixed)  # Output: [1, 'world', 3.14,      

